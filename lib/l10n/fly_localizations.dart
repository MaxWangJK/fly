class FlyLocalizationsDelegate extends LocalizationsDelegate<FlyLocalizations> {
  const FlyLocalizationsDelegate();
  @override
  bool isSupported(Locale locale) => ['zh', 'en'].contains(locale.languageCode);
  @override
  Future<FlyLocalizations> load(Locale locale) =>
      SynchronousFuture(FlyLocalizations(locale));
  @override
  bool shouldReload(FlyLocalizationsDelegate old) => false;
}

extension FlyLocalizationsContext on BuildContext {
  FlyLocalizations get l10n => FlyLocalizations.of(this);
}
